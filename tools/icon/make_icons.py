"""Writes the launcher icon and the TV banner (DESIGN.md §7.1).

The classic icon (four LED bars in its colours round a dark rectangle) with
"TV AMBIENT" inside the rectangle in our own 5×7 dot-matrix letters, drawn here as small squares: a robotic look, no
font file and nothing to license. Plain Python, no packages:

    python -I tools/icon/make_icons.py app/src/main/res

Outputs (overwritten): drawable/ic_launcher_foreground.xml, drawable/ic_launcher_background.xml,
mipmap-anydpi-v26/ic_launcher.xml (adaptive icon), drawable/banner.xml.
"""
import os
import sys

BG = "#101418"        # icon background
SCREEN = "#20262E"    # inner rectangle
TOP = "#FF5A36"       # the four LED bars
BOTTOM = "#36C2FF"
LEFT = "#8A5CFF"
RIGHT = "#36FF8A"
TEXT = "#E8ECF1"

# 5×7 dot-matrix letters, our own: each row is 5 columns, "#" lit
GLYPHS = {
    "T": ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."],
    "V": ["#...#", "#...#", "#...#", "#...#", ".#.#.", ".#.#.", "..#.."],
    "A": [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    "M": ["#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"],
    "B": ["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."],
    "I": [".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."],
    "E": ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
    "N": ["#...#", "##..#", "#.#.#", "#.#.#", "#..##", "#...#", "#...#"],
    " ": [".....", ".....", ".....", ".....", ".....", ".....", "....."],
}


def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def dots(text, x, y, pitch, fill=0.82):
    """Path data for `text` with its top-left at (x, y): each lit cell a square of pitch × fill, 1 column apart."""
    s = pitch * fill
    out = []
    cx = x
    for ch in text:
        for row, line in enumerate(GLYPHS[ch]):
            for col, c in enumerate(line):
                if c == "#":
                    out.append(f"M{num(cx + col * pitch)},{num(y + row * pitch)}h{num(s)}v{num(s)}h{num(-s)}z")
        cx += 6 * pitch
    return "".join(out)


def width(text, pitch):
    return (6 * len(text) - 1) * pitch


def rect(x, y, w, h):
    return f"M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}z"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


HEADER = "Generated by tools/icon/make_icons.py (DESIGN.md §7.1): don't edit by hand; change the script and run it again."


def main(res):
    # ---- adaptive icon, 108×108 viewport (content in the 72-unit safe zone): the classic composition, a larger screen
    bars = (f'    <path android:fillColor="{TOP}" android:pathData="{rect(18, 26, 72, 6)}" />\n'
            f'    <path android:fillColor="{BOTTOM}" android:pathData="{rect(18, 76, 72, 6)}" />\n'
            f'    <path android:fillColor="{LEFT}" android:pathData="{rect(18, 32, 6, 44)}" />\n'
            f'    <path android:fillColor="{RIGHT}" android:pathData="{rect(84, 32, 6, 44)}" />\n')
    sx, sy, sw, sh = 27, 35, 54, 38
    p_tv, p_amb = 2.3, 1.12
    tv_w, amb_w = width("TV", p_tv), width("AMBIENT", p_amb)
    tv_y = sy + 6
    amb_y = tv_y + 7 * p_tv + 4
    fg = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {HEADER} the classic icon with "TV AMBIENT" in our own dot-matrix letters. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
{bars}    <path android:fillColor="{SCREEN}" android:pathData="{rect(sx, sy, sw, sh)}" />
    <path android:fillColor="{TEXT}" android:pathData="{dots("TV", sx + (sw - tv_w) / 2, tv_y, p_tv)}" />
    <path android:fillColor="{RIGHT}" android:pathData="{dots("AMBIENT", sx + (sw - amb_w) / 2, amb_y, p_amb)}" />
</vector>
"""
    write(os.path.join(res, "drawable", "ic_launcher_foreground.xml"), fg)
    write(os.path.join(res, "drawable", "ic_launcher_background.xml"), f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{BG}" android:pathData="M0,0h108v108h-108z" />
</vector>
""")
    write(os.path.join(res, "mipmap-anydpi-v26", "ic_launcher.xml"), """<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive launcher icon (API 26+; minSdk is 26, so no legacy PNGs). No monochrome layer: TV launchers don't theme icons. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
""")

    # ---- banner, 320×180 dp (viewport 160×90): the same bars round a wide screen, "TV AMBIENT" on one line inside
    bx, by, bw, bh = 16, 16, 128, 58
    t = 4
    pitch = 1.55
    name_w = width("TV AMBIENT", pitch)
    banner = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {HEADER} the LED bars round the screen, "TV AMBIENT" in our dot-matrix letters. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="320dp" android:height="180dp"
    android:viewportWidth="160" android:viewportHeight="90">
    <path android:fillColor="{BG}" android:pathData="M0,0h160v90h-160z" />
    <path android:fillColor="{TOP}" android:pathData="{rect(bx, by - t, bw, t)}" />
    <path android:fillColor="{BOTTOM}" android:pathData="{rect(bx, by + bh, bw, t)}" />
    <path android:fillColor="{LEFT}" android:pathData="{rect(bx - t, by - t, t, bh + 2 * t)}" />
    <path android:fillColor="{RIGHT}" android:pathData="{rect(bx + bw, by - t, t, bh + 2 * t)}" />
    <path android:fillColor="{SCREEN}" android:pathData="{rect(bx + 2, by + 2, bw - 4, bh - 4)}" />
    <path android:fillColor="{TEXT}" android:pathData="{dots("TV AMBIENT", bx + (bw - name_w) / 2, by + (bh - 7 * pitch) / 2, pitch)}" />
</vector>
"""
    write(os.path.join(res, "drawable", "banner.xml"), banner)
    print("wrote icon and banner")


if __name__ == "__main__":
    main(sys.argv[1])
